"""Assembly of OpenOCD configuration from transport, CPU and chain fragments."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from soc_pastel.core.errors import ConfigurationError

_HERE = Path(__file__).parent


def fragment_path(kind: str, name: str) -> Path:
    """Return the path of a shipped fragment, e.g. ``fragment_path("cpu", "veer")``."""
    path = _HERE / kind / f"{name}.cfg"
    if not path.is_file():
        known = ", ".join(sorted(p.stem for p in (_HERE / kind).glob("*.cfg")))
        raise ConfigurationError(f"no OpenOCD {kind} fragment {name!r} (known: {known})")
    return path


@dataclass
class OpenOcdConfig:
    """An OpenOCD configuration built from fragments.

    The rendered script defines the transport first, then the JTAG chain and
    target (which must create a target called ``$_TARGETNAME``), then the CPU
    fragment, which configures that target. ``init`` is left to the driver.

    Attributes:
        transport: Tcl defining the adapter and transport.
        chain: Tcl defining the TAP(s) and creating ``$_TARGETNAME``.
        cpu: Tcl configuring ``$_TARGETNAME`` for the CPU family.
        extra: Additional Tcl appended last (ports, logging, ...).
    """

    transport: str
    chain: str
    cpu: str
    extra: list[str] = field(default_factory=list)

    def render(self) -> str:
        """Return the complete configuration script."""
        parts = [
            "# Generated by soc-pastel; do not edit.",
            "# --- transport ---",
            self.transport,
            "# --- chain ---",
            self.chain,
            "# --- cpu ---",
            self.cpu,
            *self.extra,
        ]
        return "\n".join(p.rstrip() for p in parts) + "\n"
