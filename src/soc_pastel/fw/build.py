"""Build test firmware for a device variant and code location.

The memory map is never written by hand: ``memory_map.h`` and the linker
script are generated here from the device descriptor. CPU ports may add
defines derived from the descriptor (the VeeR port computes MRAC).
"""

from __future__ import annotations

import hashlib
import os
import re
import shutil
import subprocess
from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path

from soc_pastel import FW_ROOT
from soc_pastel.core.device import CodeLocation, Device, Variant
from soc_pastel.core.errors import ConfigurationError
from soc_pastel.core.util import file_lock

#: Default stack size in bytes; override per build.
DEFAULT_STACK_SIZE = 4096


def _ident(name: str) -> str:
    return re.sub(r"[^A-Z0-9]", "_", name.upper())


def _veer_defines(device: Device, variant: Variant) -> dict[str, str]:
    """VeeR MRAC: two bits per 256 MiB region; bit 1 marks side effects."""
    mrac = 0
    for r in variant.regions:
        if r.side_effects:
            for region in range(r.base >> 28, ((r.end - 1) >> 28) + 1):
                mrac |= 0b10 << (2 * region)
    return {"PASTEL_VEER_MRAC": f"0x{mrac:08x}"}


#: Port-specific defines, keyed by CPU family.
PORT_DEFINES: dict[str, Callable[[Device, Variant], dict[str, str]]] = {
    "veer_el2": _veer_defines,
}


def memory_map_header(device: Device, variant: Variant) -> str:
    """Return the text of ``memory_map.h`` for a device variant."""
    lines = [
        "// Generated by soc-pastel from the device descriptor; do not edit.",
        "#ifndef PASTEL_MEMORY_MAP_H",
        "#define PASTEL_MEMORY_MAP_H",
        f'#define PASTEL_DEVICE "{device.name}"',
        f'#define PASTEL_VARIANT "{variant.name}"',
    ]
    for r in sorted(variant.regions, key=lambda r: r.base):
        n = _ident(r.name)
        lines += [
            f"#define PASTEL_{n}_BASE 0x{r.base:08x}u",
            f"#define PASTEL_{n}_SIZE 0x{r.size:08x}u",
        ]
    port = PORT_DEFINES.get(device.cpu.family)
    for key, value in (port(device, variant) if port else {}).items():
        lines.append(f"#define {key} {value}")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def linker_script(variant: Variant, location: CodeLocation, stack_size: int) -> str:
    """Return a linker script for a code location.

    Code goes in ``location.text``; read-only data, data, BSS and stack in
    ``location.data`` (text regions may be execute-only, e.g. an ICCM); the
    RTT control block and buffers in ``location.rtt_region``, which should be
    a memory the host can read while the CPU runs.
    """
    roles = {"TEXT": location.text, "DATA": location.data, "RTT": location.rtt_region}
    regions = {name: variant.region(name) for name in dict.fromkeys(roles.values())}

    def attrs(name: str) -> str:
        if name != location.text:
            return "rw"
        return "rwx" if name in (location.data, location.rtt_region) else "rx"

    memory = "\n".join(
        f"  {name.upper()} ({attrs(name)}) : ORIGIN = 0x{r.base:08x}, LENGTH = 0x{r.size:x}"
        for name, r in regions.items()
    )
    aliases = "\n".join(
        f'REGION_ALIAS("{role}", {region.upper()});' for role, region in roles.items()
    )
    return f"""/* Generated by soc-pastel; do not edit. */
OUTPUT_ARCH("riscv")
ENTRY(_start)
MEMORY
{{
{memory}
}}
{aliases}
SECTIONS
{{
  .text : {{ KEEP(*(.text.init)) *(.text .text.*) }} > TEXT
  .rodata : ALIGN(4) {{ *(.rodata .rodata.* .srodata .srodata.*) }} > DATA
  .data : ALIGN(4) {{ *(.data .data.*) *(.sdata .sdata.*) }} > DATA
  __global_pointer$ = ADDR(.data) + 0x800;
  .bss (NOLOAD) : ALIGN(4) {{
    __bss_start = .;
    *(.sbss .sbss.* .bss .bss.* COMMON)
    . = ALIGN(4);
    __bss_end = .;
  }} > DATA
  .stack (NOLOAD) : ALIGN(16) {{ . += {stack_size}; __stack_top = .; }} > DATA
  .rtt (NOLOAD) : ALIGN(4) {{ KEEP(*(.rtt .rtt.*)) }} > RTT
  /DISCARD/ : {{ *(.comment) *(.riscv.attributes) }}
}}
"""


@dataclass(frozen=True)
class Toolchain:
    """A GNU RISC-V cross toolchain.

    The prefix defaults to ``$PASTEL_RISCV_PREFIX`` or ``riscv64-unknown-elf-``.
    """

    prefix: str = ""

    def tool(self, name: str) -> str:
        """Return the full command for a tool, e.g. ``gcc``."""
        prefix = self.prefix or os.environ.get("PASTEL_RISCV_PREFIX", "riscv64-unknown-elf-")
        cmd = prefix + name
        if shutil.which(cmd) is None:
            raise ConfigurationError(f"{cmd} not found; set PASTEL_RISCV_PREFIX")
        return cmd


def runtime_sources(device: Device) -> list[Path]:
    """Firmware runtime sources for the device's CPU port."""
    port = FW_ROOT / "ports" / device.cpu.family
    if not port.is_dir():
        raise ConfigurationError(f"no firmware port for CPU family {device.cpu.family!r}")
    return sorted((FW_ROOT / "runtime").glob("*.c")) + sorted(port.glob("*.[cS]"))


def build_firmware(
    device: Device,
    variant: Variant,
    location: CodeLocation,
    sources: Sequence[Path],
    out_dir: Path,
    *,
    include_dirs: Iterable[Path] = (),
    defines: Iterable[str] = (),
    stack_size: int = DEFAULT_STACK_SIZE,
    toolchain: Toolchain | None = None,
) -> Path:
    """Compile and link test firmware; return the ELF path.

    Results are cached in ``out_dir`` by a hash of every input, so repeated
    builds (e.g. once per test) are free.
    """
    tc = toolchain or Toolchain()
    sources = [Path(s).resolve() for s in sources]
    all_sources = runtime_sources(device) + sources
    header = memory_map_header(device, variant)
    script = linker_script(variant, location, stack_size)
    flags = [
        f"-march={device.cpu.isa}",
        f"-mabi={device.cpu.abi}",
        "-Os",
        "-g",
        "-ffreestanding",
        "-fno-builtin",
        "-nostdlib",
        "-nostartfiles",
        "-Wall",
        "-Wl,--gc-sections",
        "-Wl,--no-warn-rwx-segments",
        "-ffunction-sections",
        "-fdata-sections",
        *(f"-D{d}" for d in defines),
    ]
    h = hashlib.sha256()
    for part in (header, script, " ".join(flags), tc.tool("gcc"), str(stack_size)):
        h.update(part.encode())
    for src in all_sources:
        h.update(str(src).encode())
        h.update(src.read_bytes())
    stem = (sources[0].stem if sources else "firmware") + f"-{location.name}"
    work = out_dir / f"{stem}-{h.hexdigest()[:12]}"
    elf = work / f"{stem}.elf"
    if elf.is_file():
        return elf
    with file_lock(work.with_suffix(".lock")):  # parallel test workers share builds
        if elf.is_file():
            return elf
        _compile(tc, flags, header, script, all_sources, include_dirs, work, elf)
    return elf


def _compile(
    tc: Toolchain,
    flags: list[str],
    header: str,
    script: str,
    all_sources: list[Path],
    include_dirs: Iterable[Path],
    work: Path,
    elf: Path,
) -> None:
    gen = work / "gen"
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "memory_map.h").write_text(header)
    (gen / "link.ld").write_text(script)
    incs = [gen, FW_ROOT / "include", FW_ROOT / "runtime", *map(Path, include_dirs)]
    cmd = [
        tc.tool("gcc"),
        *flags,
        *(f"-I{i}" for i in incs),
        "-include",
        str(gen / "memory_map.h"),
        "-T",
        str(gen / "link.ld"),
        "-o",
        str(elf),
        *map(str, all_sources),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    (work / "build.log").write_text(" ".join(cmd) + "\n\n" + result.stdout + result.stderr)
    if result.returncode != 0:
        raise ConfigurationError(f"firmware build failed:\n{result.stderr}")
